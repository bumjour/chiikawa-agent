const INTERVALS = { often: [15, 30], sometimes: [40, 80] };

function nextDelayMs(freq) {
  const [a, b] = INTERVALS[freq] || INTERVALS.sometimes;
  return (a + Math.random() * (b - a)) * 60 * 1000;
}

